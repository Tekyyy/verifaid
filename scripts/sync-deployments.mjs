#!/usr/bin/env node
/**
 * Bundles deployments/*.json into services/shared/src/generated/deployments.ts so every package — including the
 * browser bundle, which cannot read the filesystem — imports the same typed addresses and schema UIDs.
 *
 *   pnpm sync:deployments   (also run automatically before building @poa/shared)
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const deploymentsDir = join(root, 'deployments')
const outFile = join(root, 'services', 'shared', 'src', 'generated', 'deployments.ts')

const deployments = {}
if (existsSync(deploymentsDir)) {
  // Archived releases (e.g. base-sepolia.v1.json) stay on disk as a record but are not bundled.
  const current = readdirSync(deploymentsDir).filter((f) => f.endsWith('.json') && !/\.v\d+\.json$/.test(f))
  for (const file of current) {
    const parsed = JSON.parse(readFileSync(join(deploymentsDir, file), 'utf8'))
    deployments[parsed.network ?? file.replace(/\.json$/, '')] = parsed
  }
}

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(
  outFile,
  `// Generated by scripts/sync-deployments.mjs from deployments/*.json — do not edit by hand.
import type { Deployment } from '../types.js'

export const deployments = ${JSON.stringify(deployments, null, 2)} as unknown as Record<string, Deployment>
`,
)
console.log(
  `wrote ${Object.keys(deployments).length} deployment(s) to services/shared/src/generated/deployments.ts`,
)
